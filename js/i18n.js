// ============================================================ Mécanique
function L() { return I18N[Settings.v.lang] || I18N.fr; }
// t('clé', { variable: valeur }) : texte de l'interface dans la langue choisie (repli sur le français)
function t(key, vars) {
  let s = L().ui[key];
  if (s == null) s = I18N.fr.ui[key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}
function seasonLabel(se) { return se.name.replace(/^\S+\s+/, ''); }  // sans l'emoji

// Notes de version dans la langue choisie (le français vient de js/changelog.js)
function changelogEntries() {
  const tr = (L().content && L().content.changelog) || {};
  return CHANGELOG.map(e => Object.assign({}, e, tr[e.version] || {}));
}

// Recopie les textes de la langue choisie dans les données (g.name, u.desc…), pour que le reste du code les lise directement
function applyContentText() {
  const C = L().content, F = I18N.fr.content;
  const get = (tbl, id) => (C[tbl] && C[tbl][id]) || F[tbl][id] || [];
  for (const g of GENERATORS) [g.name, g.desc] = get('gens', g.id);
  for (const se of SEASONS) [se.name, se.hint] = get('seasons', se.id);
  const tiers = C.tiers || F.tiers;
  for (const u of UPGRADES) {
    const tx = get('upgrades', u.id);
    if (u.type === 'gen') {
      const g = GENERATORS.find(x => x.id === u.target);
      u.name = t('upg.genName', { tier: tiers[u.tier], gen: g.name });
      u.desc = t('upg.genDesc', { gen: g.name, m: u.mult });
      u.hint = t('upg.genHint', { gen: g.name, n: u.at });
    } else if (u.type === 'click') {
      u.name = tx[0];
      u.desc = tx[1] || t('upg.clickDesc', { p: Math.round(u.pct * 100) });
      u.hint = t('upg.clickHint', { n: fmt(u.clicks) });
    } else {
      u.name = tx[0];
      u.desc = tx[1] || t('upg.globalDesc', { p: Math.round((u.mult - 1) * 100) });
      u.hint = tx[2] || t('upg.globalHint', { n: fmt(u.need) });
    }
  }
  for (const a of ACHIEVEMENTS) [a.name, a.desc] = get('ach', a.id);
  for (const b of TALENT_BRANCHES) b.name = (C.branches && C.branches[b.id]) || F.branches[b.id];
  for (const x of TALENTS) [x.name, x.desc] = get('talents', x.id);
  for (const u of SUGAR_UPGRADES) [u.name, u.desc] = get('sugarUpg', u.id);
  for (const sp of SPECIES) {
    const tx = get('species', sp.id);
    [sp.name, sp.style, sp.desc] = tx;
    if (sp.unlock) sp.unlock.text = tx[3];
  }
  for (const c of CHALLENGES) [c.name, c.ruleText, c.reward] = get('challenges', c.id);  // v11 : c.rule = contrainte (data.js)
  for (const r of RELICS) [r.name, r.desc] = get('relics', r.id);
  for (const x of SPECIMENS) [x.name, x.note, x.effect] = get('specimens', x.id);
  for (const n of NOTES) [n.title, n.text] = get('notes', n.id);
  for (const g of GUIDE) g.text = (C.guide && C.guide[g.id]) || F.guide[g.id];
}

// Textes fixes de la page : data-i18n (texte), data-i18n-html (avec balises), data-i18n-title, data-i18n-ph (placeholder)
function applyPageText(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(e => { e.innerHTML = t(e.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach(e => { e.title = t(e.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-ph]').forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
  document.documentElement.lang = Settings.v.lang;
  document.title = (SANDBOX ? t('sandbox.title', { name: SANDBOX }) : '') + t('doc.title');
}

